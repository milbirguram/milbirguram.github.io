// Precomputes the figures the page shows from model.js: the guided steps over many seeds and the
// phase map. Run: node projects/undertow/tools/build-data.js   (writes projects/undertow/data.js)
// tests/data.test.js recomputes these and fails if data.js is out of date.
'use strict';
var fs = require('fs');
var path = require('path');
var M = require(path.join(__dirname, '..', 'model.js'));

function compute(log) {
  var steps = M.STEPS.map(function (st) {
    var f = M.stepFigures(st);
    if (log) log('step ' + st.key + ': ' + JSON.stringify(f));
    return f;
  });
  var cells = M.PHASE.rows.map(function (row) {
    var r = M.PHASE.factors.map(function (f) { return M.phaseCell(row.key, f); });
    if (log) log('phase ' + row.key + ': ' + r.join(' '));
    return r;
  });
  return {
    steps: steps,
    phase: { factors: M.PHASE.factors, rows: M.PHASE.rows.map(function (r) { return r.key; }), seeds: M.PHASE.seeds, recovered: cells }
  };
}

function render(data) {
  return '// Generated by tools/build-data.js from model.js. Do not edit by hand.\n' +
    '// tests/data.test.js recomputes every figure and fails if this file is stale.\n' +
    '(function (root) {\n  var data = ' + JSON.stringify(data) + ';\n' +
    "  if (typeof module !== 'undefined' && module.exports) module.exports = data;\n" +
    '  else root.UndertowData = data;\n' +
    "})(typeof window !== 'undefined' ? window : this);\n";
}

if (require.main === module) {
  var t0 = Date.now();
  var data = compute(console.log);
  fs.writeFileSync(path.join(__dirname, '..', 'data.js'), render(data));
  console.log('wrote data.js in ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s');
}

module.exports = { compute: compute, render: render };
